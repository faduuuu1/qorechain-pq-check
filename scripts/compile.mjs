/**
 * compile.mjs - compile a contract in `contracts/` to a typed artifact.
 *
 *   node scripts/compile.mjs PqcGate
 *
 * Writes `contracts/<Name>.artifact.ts` exporting `<name>Abi` as a `const`
 * tuple (so viem can infer typed calls) and `<name>Bytecode` as a `Hex`.
 *
 * The repo has no solc binary and no hardhat/foundry toolchain: the EVM lane is
 * exercised through viem, and a whole build framework to compile two contracts
 * would be more moving parts than the thing it builds. solc-js pinned to 0.8.24
 * matches the pragma and the compiler that produced Counter.artifact.ts.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { basename } from "node:path";
import solc from "solc";

const name = process.argv[2];
if (!name) {
  console.error("Usage: node scripts/compile.mjs <ContractName>");
  process.exit(1);
}

const file = `${name}.sol`;
const source = readFileSync(new URL(`../contracts/${file}`, import.meta.url), "utf8");

const input = {
  language: "Solidity",
  sources: { [file]: { content: source } },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } },
  },
};

const output = JSON.parse(solc.compile(JSON.stringify(input)));

const errors = (output.errors ?? []).filter((e) => e.severity === "error");
if (errors.length) {
  for (const e of errors) console.error(e.formattedMessage ?? e.message);
  process.exit(1);
}
for (const w of (output.errors ?? []).filter((e) => e.severity === "warning")) {
  console.warn(w.formattedMessage ?? w.message);
}

const contract = output.contracts?.[file]?.[name];
if (!contract) {
  console.error(`solc produced no contract named ${name} in ${file}.`);
  console.error(`found: ${Object.keys(output.contracts?.[file] ?? {}).join(", ") || "nothing"}`);
  process.exit(1);
}

const bytecode = `0x${contract.evm.bytecode.object}`;
const lower = name.charAt(0).toLowerCase() + name.slice(1);
const version = solc.version().split("+")[0];

const artifact = `/**
 * Compiled artifact for \`contracts/${file}\`.
 *
 * Generated by \`npm run compile -- ${name}\` with solc ${version} (--optimize,
 * 200 runs). Do not edit by hand: edit the .sol file and regenerate. The ABI is
 * exported as a \`const\` tuple so viem can infer fully-typed read/write calls.
 */
import type { Hex } from "viem";

export const ${lower}Abi = ${JSON.stringify(contract.abi, null, 2)} as const;

/** Creation bytecode (\`0x\`-prefixed). */
export const ${lower}Bytecode: Hex =
  "${bytecode}";
`;

const out = new URL(`../contracts/${name}.artifact.ts`, import.meta.url);
writeFileSync(out, artifact);

console.log(`solc      ${version}`);
console.log(`contract  ${name}`);
console.log(`abi       ${contract.abi.length} entries`);
console.log(`bytecode  ${(bytecode.length - 2) / 2} bytes`);
console.log(`written   contracts/${basename(out.pathname)}`);
